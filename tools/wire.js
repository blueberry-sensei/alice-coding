function buildOwnedTargets(prompt) {
  const description = "Nạp base prompt ALICE đã bake và bắt đầu một task vibe coding theo đúng rules, memory, telemetry và verify của project.";
  const portable = markdownAdapter(
    [
      "name: alice",
      `description: ${description}`,
    ],
    prompt,
    "Nội dung người dùng viết cùng lời gọi skill `$alice` là nhiệm vụ cần thực hiện. Nếu chưa có nhiệm vụ, hỏi đúng một câu ngắn để lấy nhiệm vụ.",
  );
  const claude = markdownAdapter(
    [
      "name: alice",
      `description: ${description}`,
      "disable-model-invocation: true",
      "argument-hint: <task>",
    ],
    prompt,
    "$ARGUMENTS",
  );
  const opencode = markdownAdapter(
    [
      `description: ${description}`,
    ],
    prompt,
    "$ARGUMENTS",
  );
  const geminiPrompt = [
    `<!-- ${MARKER} -->`,
    "Nạp toàn bộ chỉ dẫn dưới đây làm chỉ dẫn đứng cho phiên làm việc hiện tại.",
    "Nếu có xung đột, system/developer instruction và luật project có ưu tiên cao hơn.",
    "",
    prompt,
    "",
    "## NHIỆM VỤ CỦA LƯỢT NÀY",
    "{{args}}",
  ].join("\n");
  const gemini = [
    `# ${MARKER}`,
    `description = ${JSON.stringify(description)}`,
    `prompt = ${JSON.stringify(geminiPrompt)}`,
    "",
  ].join("\n");

  return [
    [path.join(PROJECT_ROOT, "ALICE.md"), rootEntryPoint(prompt), "Project entry point"],
    [path.join(PROJECT_ROOT, ".agents", "skills", "alice", "SKILL.md"), portable, "Codex/OpenCode skill"],
    [path.join(PROJECT_ROOT, ".claude", "skills", "alice", "SKILL.md"), claude, "Claude Code skill"],
    [path.join(PROJECT_ROOT, ".opencode", "commands", "alice.md"), opencode, "OpenCode command"],
    [path.join(PROJECT_ROOT, ".gemini", "commands", "alice.toml"), gemini, "Gemini CLI command"],
  ];
}

/** File auto-load của từng client. Nội dung người dùng KHÔNG bị đụng. */
const AUTO_CONTEXT_FILES = [
  ["CLAUDE.md", "Claude Code auto-context"],
  ["AGENTS.md", "Codex/OpenCode auto-context"],
  ["GEMINI.md", "Gemini CLI auto-context"],
];

function isAliceOwned(file) {
  return fs.existsSync(file) && fs.readFileSync(file, "utf8").includes(MARKER);
}

function writeOwned(targets) {
  const conflicts = targets
    .filter(([file]) => fs.existsSync(file) && !isAliceOwned(file))
    .map(([file]) => path.relative(PROJECT_ROOT, file));
  if (conflicts.length) {
    fail(`refusing to overwrite non-ALICE file(s): ${conflicts.join(", ")}`, 2);
  }

  for (const [file, content, label] of targets) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, "utf8");
    console.log(`  ${"WIRED".padEnd(7)} ${label}: ${path.relative(PROJECT_ROOT, file)}`);
  }
}

function mergeBlock(existing, block) {
  const begin = existing.indexOf(BLOCK_BEGIN);
  const end = existing.indexOf(BLOCK_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    return existing.slice(0, begin) + block + existing.slice(end + BLOCK_END.length);
  }
  const head = existing.trim();
  return head ? `${head}\n\n${block}\n` : `${block}\n`;
}

function writeAutoContext() {
  for (const [name, label] of AUTO_CONTEXT_FILES) {
    const file = path.join(PROJECT_ROOT, name);
    const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    const next = mergeBlock(existing, autoContextBlock());
    if (next === existing) {
      console.log(`  ${"OK".padEnd(7)} ${label}: ${name} (already current)`);
      continue;
    }
    fs.writeFileSync(file, next, "utf8");
    console.log(`  ${(existing ? "UPDATED" : "WIRED").padEnd(7)} ${label}: ${name}`);
  }
}

/**
 * Hook SessionStart của Claude Code: sau mỗi lần compact, in lại ALICE.md vào context.
 *
 * Đây là lớp duy nhất chạy NGOÀI model, nên là thứ duy nhất không bị auto-compact xoá.
 * Chỉ thêm hook mang đúng command của ALICE; mọi key khác trong settings.json giữ nguyên.
 */
function writeClaudeHook() {
  const file = path.join(PROJECT_ROOT, ".claude", "settings.json");
  let settings = {};
  if (fs.existsSync(file)) {
    const raw = fs.readFileSync(file, "utf8").trim();
    if (raw) {
      try {
        settings = JSON.parse(raw);
      } catch (error) {
        console.warn(
          `  SKIP   Claude Code compact hook: .claude/settings.json is not valid JSON (${error.message}).`,
        );
        console.warn("         Fix the file and run `npm run wire` again to install the hook.");
        return false;
      }
    }
  }
  if (!settings || typeof settings !== "object" || Array.isArray(settings)) {
    console.warn("  SKIP   Claude Code compact hook: .claude/settings.json is not a JSON object.");
    return false;
  }

  const hooks = settings.hooks && typeof settings.hooks === "object" ? settings.hooks : {};
  const sessionStart = Array.isArray(hooks.SessionStart) ? hooks.SessionStart : [];
  const owned = (entry) =>
    Array.isArray(entry && entry.hooks) &&
    entry.hooks.some((hook) => typeof hook.command === "string" && hook.command.includes("tools/reminder.js"));
  // KHÔNG đặt `matcher`. `SessionStart` phân biệt phiên bằng `source`
  // (`startup|resume|clear|compact|fork`) và tài liệu của Claude Code ghi matcher của event
  // này là "-". Bỏ trống thì hook chạy cho mọi source, kể cả `compact` — đúng thứ cần. Viết
  // một chuỗi alternation vào đây là đặt cược rằng matcher được so bằng regex chứ không phải
  // so bằng chuỗi; đoán sai thì hook im lặng không bao giờ chạy.
  const entry = {
    hooks: [{ type: "command", command: REMINDER_COMMAND }],
  };
  const next = sessionStart.filter((item) => !owned(item)).concat([entry]);

  settings.hooks = Object.assign({}, hooks, { SessionStart: next });
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(settings, null, 2)}\n`, "utf8");
  console.log(`  ${"WIRED".padEnd(7)} Claude Code compact hook: .claude/settings.json`);
  return true;
}

const baked = stripTaskSection(readBakedPrompt());
writeOwned(buildOwnedTargets(baked));
writeAutoContext();
const hooked = writeClaudeHook();

console.log("\nALICE entry points are ready:");
console.log("  Claude Code / OpenCode / Gemini CLI: /alice <task>");
console.log("  Codex: $alice <task> (Codex does not expose repo skills as /alice)");
console.log("  Any other agent: attach ALICE.md and write the task");
console.log("  CLAUDE.md / AGENTS.md / GEMINI.md carry the rules even when nobody calls /alice");
if (hooked) {
  console.log("  Claude Code reloads ALICE.md automatically after every auto-compact");
}
console.log("Commit the generated files with the project so the team gets the same entry point.");
