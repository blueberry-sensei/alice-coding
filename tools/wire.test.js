"use strict";

const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");
const test = require("node:test");

const SOURCE = path.join(__dirname, "wire.js");
const REMINDER_SOURCE = path.join(__dirname, "reminder.js");

const BAKED = "# Base\n\nProject demo.\n\n## NHIỆM VỤ\n<đã bake>";

function fixture(prompt = BAKED) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "alice-wire-"));
  const knowledge = path.join(root, "project", "knowledge");
  const tools = path.join(knowledge, "tools");
  fs.mkdirSync(tools, { recursive: true });
  fs.copyFileSync(SOURCE, path.join(tools, "wire.js"));
  fs.copyFileSync(REMINDER_SOURCE, path.join(tools, "reminder.js"));
  fs.writeFileSync(path.join(knowledge, "prompts.md"), prompt, "utf8");
  const project = path.join(root, "project");
  return {
    root,
    project,
    knowledge,
    read: (rel) => fs.readFileSync(path.join(project, rel), "utf8"),
    run: () => spawnSync(process.execPath, [path.join(tools, "wire.js")], { encoding: "utf8" }),
    reminder: () =>
      spawnSync(process.execPath, [path.join(tools, "reminder.js")], {
        cwd: project,
        encoding: "utf8",
      }),
    cleanup: () => fs.rmSync(root, { recursive: true, force: true }),
  };
}

const ADAPTERS = [
  ".agents/skills/alice/SKILL.md",
  ".claude/skills/alice/SKILL.md",
  ".opencode/commands/alice.md",
  ".gemini/commands/alice.toml",
];

test("wire creates and refreshes every supported project adapter", () => {
  const fx = fixture();
  try {
    const first = fx.run();
    assert.strictEqual(first.status, 0, first.stderr);

    for (const rel of ADAPTERS) {
      const content = fx.read(rel);
      assert.match(content, /Generated by ALICE CODING/);
      assert.match(content, /Project demo/);
    }
    const gemini = fx.read(ADAPTERS[3]);
    const promptLine = gemini.split(/\r?\n/).find((line) => line.startsWith("prompt = "));
    assert.ok(promptLine);
    assert.match(JSON.parse(promptLine.slice("prompt = ".length)), /\{\{args\}\}/);

    fs.writeFileSync(
      path.join(fx.knowledge, "prompts.md"),
      "# Base\n\nProject demo v2.\n\n## NHIỆM VỤ\n<đã bake>",
      "utf8",
    );
    const second = fx.run();
    assert.strictEqual(second.status, 0, second.stderr);
    assert.match(fx.read(ADAPTERS[0]), /Project demo v2/);
  } finally {
    fx.cleanup();
  }
});

test("wire drops the stale task section so only one task block survives", () => {
  const fx = fixture("# Base\n\nProject demo.\n\n## NHIỆM VỤ\nviệc cũ còn sót lại");
  try {
    assert.strictEqual(fx.run().status, 0);
    for (const rel of ADAPTERS) {
      assert.doesNotMatch(fx.read(rel), /việc cũ còn sót lại/);
    }
    assert.doesNotMatch(fx.read("ALICE.md"), /việc cũ còn sót lại/);
  } finally {
    fx.cleanup();
  }
});

