#!/usr/bin/env node
/**
 * wire — sinh entry point ALICE cho project từ base prompt đã bake.
 *
 * Chỉ dùng Node built-in. Script chạy trong knowledge/ và ghi vào project cha.
 *
 * Ba lớp entry point, cố ý khác nhau về cơ chế:
 *   1. ALICE.md ở root  — file Bệ hạ đính kèm thủ công cho agent nào cũng dùng được.
 *   2. CLAUDE.md / AGENTS.md / GEMINI.md — client TỰ nạp mỗi phiên, không cần gõ gì.
 *      Đây là lớp duy nhất còn hiệu lực khi người dùng quên gọi /alice.
 *   3. Skill/command `/alice` — nạp trọn base prompt khi được gọi tường minh.
 *
 * File đã có mà không mang marker ALICE sẽ KHÔNG bị ghi đè. Với ba file auto-load ở
 * lớp 2, chỉ khối giữa hai marker bị thay; nội dung của người dùng giữ nguyên.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PROJECT_ROOT = path.resolve(ROOT, "..");
const KNOWLEDGE_DIR = path.basename(ROOT);
const PROMPT_FILE = path.join(ROOT, "prompts.md");
const MARKER = "Generated by ALICE CODING. Source: knowledge/prompts.md.";
const BLOCK_BEGIN = "<!-- BEGIN ALICE CODING -->";
const BLOCK_END = "<!-- END ALICE CODING -->";
const REMINDER_COMMAND = `node ${KNOWLEDGE_DIR}/tools/reminder.js`;

function fail(message, code = 1) {
  console.error(`ALICE wire failed: ${message}`);
  process.exit(code);
}

function readBakedPrompt() {
  if (!fs.existsSync(PROMPT_FILE)) {
    fail("prompts.md was not found. Complete INITIALIZATION Step 7 first.");
  }
  const prompt = fs.readFileSync(PROMPT_FILE, "utf8").trim();
  if (!prompt) fail("prompts.md is empty.");
  if (!prompt.includes("## NHIỆM VỤ")) {
    fail("prompts.md is not an ALICE vibe base prompt (missing '## NHIỆM VỤ').");
  }
  const placeholders = ["<PROJECT>", "<Bệ hạ chỉ cần điền việc cần làm ở đây>"];
  const unresolved = placeholders.find((value) => prompt.includes(value));
  if (unresolved) {
    fail(`prompts.md still contains the unresolved placeholder ${unresolved}.`);
  }
  return prompt;
}

/**
 * Cắt phần "## NHIỆM VỤ" khỏi base prompt.
 *
 * Mỗi target tự gắn khối nhiệm vụ theo cú pháp của chính client ($ARGUMENTS, {{args}}...).
 * Giữ lại khối cũ của prompts.md sẽ để hai mục NHIỆM VỤ chồng nhau trong cùng một file,
 * và agent không biết mục nào là việc thật của lượt này.
 */
function stripTaskSection(prompt) {
  const lines = prompt.split(/\r?\n/);
  const start = lines.reduce(
    (found, line, index) => (/^#{1,6}\s*NHIỆM VỤ\s*$/.test(line.trim()) ? index : found),
    -1,
  );
  if (start === -1) return prompt.trim();
  return lines.slice(0, start).join("\n").trim();
}

function markdownAdapter(frontmatter, prompt, taskBlock) {
  return [
    "---",
    ...frontmatter,
    "---",
    "",
    `<!-- ${MARKER} -->`,
    "",
    "Nạp toàn bộ chỉ dẫn dưới đây làm chỉ dẫn đứng cho phiên làm việc hiện tại.",
    "Nếu có xung đột, system/developer instruction và luật project có ưu tiên cao hơn.",
    "",
    prompt,
    "",
    "## NHIỆM VỤ CỦA LƯỢT NÀY",
    taskBlock,
    "",
  ].join("\n");
}

