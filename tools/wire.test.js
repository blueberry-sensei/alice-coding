test("wire injects the rules block into auto-context files without eating user content", () => {
  const fx = fixture();
  try {
    fs.writeFileSync(path.join(fx.project, "AGENTS.md"), "# Luật riêng của team\n\nGiữ nguyên dòng này.\n", "utf8");
    assert.strictEqual(fx.run().status, 0);

    for (const name of ["CLAUDE.md", "AGENTS.md", "GEMINI.md"]) {
      const content = fx.read(name);
      assert.match(content, /<!-- BEGIN ALICE CODING -->/);
      assert.match(content, /<!-- END ALICE CODING -->/);
      assert.match(content, /Nạp ký ức trước mọi task/);
      // Khối auto-load cố ý KHÔNG chép cả base prompt: nó đi kèm mọi request.
      assert.doesNotMatch(content, /Project demo/);
    }
    assert.match(fx.read("AGENTS.md"), /Giữ nguyên dòng này/);

    // Chạy lại: khối được thay tại chỗ, không nhân bản, nội dung người dùng còn nguyên.
    assert.strictEqual(fx.run().status, 0);
    const agents = fx.read("AGENTS.md");
    assert.strictEqual(agents.match(/<!-- BEGIN ALICE CODING -->/g).length, 1);
    assert.match(agents, /Giữ nguyên dòng này/);
  } finally {
    fx.cleanup();
  }
});

test("wire installs the compact hook and keeps foreign settings intact", () => {
  const fx = fixture();
  try {
    const settingsFile = path.join(fx.project, ".claude", "settings.json");
    fs.mkdirSync(path.dirname(settingsFile), { recursive: true });
    fs.writeFileSync(
      settingsFile,
      JSON.stringify({
        permissions: { allow: ["Bash(npm run verify)"] },
        hooks: { SessionStart: [{ matcher: "startup", hooks: [{ type: "command", command: "echo mine" }] }] },
      }),
      "utf8",
    );

    assert.strictEqual(fx.run().status, 0);
    let settings = JSON.parse(fs.readFileSync(settingsFile, "utf8"));
    assert.deepStrictEqual(settings.permissions.allow, ["Bash(npm run verify)"]);
    assert.strictEqual(settings.hooks.SessionStart.length, 2);
    assert.strictEqual(settings.hooks.SessionStart[0].hooks[0].command, "echo mine");
    const alice = settings.hooks.SessionStart[1];
    // Không có matcher = chạy cho mọi source của SessionStart, kể cả `compact`.
    assert.strictEqual("matcher" in alice, false);
    assert.match(alice.hooks[0].command, /tools\/reminder\.js$/);

    // Chạy lại không được nhân đôi hook của ALICE.
    assert.strictEqual(fx.run().status, 0);
    settings = JSON.parse(fs.readFileSync(settingsFile, "utf8"));
    assert.strictEqual(settings.hooks.SessionStart.length, 2);
  } finally {
    fx.cleanup();
  }
});

test("wire keeps a broken settings.json instead of clobbering it", () => {
  const fx = fixture();
  try {
    const settingsFile = path.join(fx.project, ".claude", "settings.json");
    fs.mkdirSync(path.dirname(settingsFile), { recursive: true });
    fs.writeFileSync(settingsFile, "{ not json", "utf8");

    const result = fx.run();
    assert.strictEqual(result.status, 0, result.stderr);
    assert.match(result.stderr, /SKIP\s+Claude Code compact hook/);
    assert.strictEqual(fs.readFileSync(settingsFile, "utf8"), "{ not json");
    // Phần còn lại vẫn phải được sinh, không vì hook hỏng mà bỏ dở.
    assert.match(fx.read("ALICE.md"), /Project demo/);
  } finally {
    fx.cleanup();
  }
});

test("reminder replays the generated entry point for the compact hook", () => {
  const fx = fixture();
  try {
    assert.strictEqual(fx.run().status, 0);
    const result = fx.reminder();
    assert.strictEqual(result.status, 0, result.stderr);
    assert.match(result.stdout, /<alice-entry-point>/);
    assert.match(result.stdout, /Project demo/);
    assert.match(result.stdout, /auto-compact/);
  } finally {
    fx.cleanup();
  }
});

test("reminder stays quiet on stdout when the entry point is missing", () => {
  const fx = fixture();
  try {
    const result = fx.reminder();
    assert.strictEqual(result.status, 0);
    assert.strictEqual(result.stdout, "");
    assert.match(result.stderr, /ALICE\.md was not found/);
  } finally {
    fx.cleanup();
  }
});

test("wire refuses all writes when an alice adapter belongs to the user", () => {
  const fx = fixture();
  try {
    const conflict = path.join(fx.project, ".claude", "skills", "alice", "SKILL.md");
    fs.mkdirSync(path.dirname(conflict), { recursive: true });
    fs.writeFileSync(conflict, "user-owned command", "utf8");

    const result = fx.run();
    assert.strictEqual(result.status, 2);
    assert.match(result.stderr, /refusing to overwrite non-ALICE file/);
    assert.strictEqual(
      fs.existsSync(path.join(fx.project, ".agents", "skills", "alice", "SKILL.md")),
      false,
    );
    assert.strictEqual(fs.existsSync(path.join(fx.project, "ALICE.md")), false);
    assert.strictEqual(fs.readFileSync(conflict, "utf8"), "user-owned command");
  } finally {
    fx.cleanup();
  }
});

test("wire refuses to overwrite a project ALICE.md it did not write", () => {
  const fx = fixture();
  try {
    fs.writeFileSync(path.join(fx.project, "ALICE.md"), "# Tài liệu của Bệ hạ\n", "utf8");
    const result = fx.run();
    assert.strictEqual(result.status, 2);
    assert.match(result.stderr, /ALICE\.md/);
    assert.strictEqual(fx.read("ALICE.md"), "# Tài liệu của Bệ hạ\n");
  } finally {
    fx.cleanup();
  }
});

